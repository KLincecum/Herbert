"""Generate static support labels/messages from production source, never run data."""
from pathlib import Path
import json,re

def block_end(text,start):
    depth=1;i=start+1
    while i<len(text):
        if text.startswith('//',i):
            end=text.find('\n',i+2);i=len(text) if end<0 else end+1;continue
        if text.startswith('/*',i):
            comments=1;i+=2
            while i<len(text) and comments:
                if text.startswith('/*',i):comments+=1;i+=2
                elif text.startswith('*/',i):comments-=1;i+=2
                else:i+=1
            continue
        raw=re.match(r'(?:br|r)(#*)"',text[i:])
        if raw:
            closing='"'+raw.group(1);end=text.find(closing,i+len(raw.group(0)))
            if end<0:raise ValueError('Unclosed Rust raw string')
            i=end+len(closing);continue
        if text[i]=='"':
            i+=1
            while i<len(text):
                if text[i]=='\\':i+=2
                elif text[i]=='"':i+=1;break
                else:i+=1
            continue
        if text[i]=="'":
            char=re.match(r"'(?:\\(?:u\{[0-9a-fA-F_]+\}|x[0-9a-fA-F]{2}|.)|[^'\\\n])'",text[i:])
            if char:i+=len(char.group(0));continue
        if text[i]=='{':depth+=1
        elif text[i]=='}':
            depth-=1
            if depth==0:return i+1
        i+=1
    raise ValueError('Unclosed Rust test module')

TEST_MODULE=re.compile(r'#\s*\[\s*cfg\s*\(\s*test\s*\)\s*\]\s*(?:#\[[^\]]*\]\s*)*mod\s+\w+\s*\{')
def production_source(text):
    pieces=[];pos=0
    while match:=TEST_MODULE.search(text,pos):
        pieces.append(text[pos:match.start()]);pos=block_end(text,match.end()-1)
    pieces.append(text[pos:]);return ''.join(pieces)

def generate(root):
    words=set();messages=set()
    for crate in ('herbert','herbert-plugins','herbert-contract'):
        for path in (root/'crates'/crate/'src').rglob('*'):
            if path.suffix not in ('.rs','.json') or path.name.startswith('support_') or path.name.endswith('_tests.rs') or path.name=='tests.rs':continue
            text=production_source(path.read_text(encoding='utf-8'))
            words.update(re.findall(r'"([A-Za-z][A-Za-z0-9_.-]*)"',text))
            if path.suffix!='.rs':continue
            for token in re.findall(r'"(?:[^"\\]|\\.)*"',text):
                try:value=json.loads(token)
                except ValueError:continue
                if ' ' in value and not any(c in value for c in '{}<>'):messages.add(value)
    # These public labels are generated by serde rather than literal Rust text.
    contract=(root/'crates/herbert-contract/src/lib.rs').read_text(encoding='utf-8')
    settings=contract.split('pub struct OperatingSettings {',1)[1].split('}',1)[0]
    for name in re.findall(r'pub ([a-z_]+):',settings):
        first,*rest=name.split('_');words.add(first+''.join(p.title() for p in rest))
    words.update(('session','basicApiKey','global','company','personal','sharedCompany'))
    # The token route is stored as api/TokenResource; failed-request context
    # reports its two path segments, both public transport labels.
    words.update(('api','TokenResource'))
    return words,messages

if __name__=='__main__':
    root=Path(__file__).resolve().parents[1];words,messages=generate(root)
    (root/'crates/herbert/src/support_vocabulary.txt').write_text('\n'.join(sorted(words))+'\n',encoding='utf-8')
    (root/'crates/herbert/src/support_messages.json').write_text(json.dumps(sorted(messages),ensure_ascii=False)+'\n',encoding='utf-8')
    print(f'{len(words)} support labels, {len(messages)} static authored messages')
